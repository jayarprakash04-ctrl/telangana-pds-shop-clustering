"""
Telangana PDS Shop Performance Dashboard
Run with: streamlit run app.py
Expects outputs/shop_features_clustered.csv (generated by your analysis notebook)
"""

import pandas as pd
import streamlit as st
import folium
from streamlit_folium import st_folium

st.set_page_config(page_title="Telangana PDS Shop Analytics", layout="wide")


@st.cache_data
def load_data():
    return pd.read_csv("outputs/shop_features_clustered.csv")


CLUSTER_NAMES = {
    0: "Low-Volume Rural / Steady",
    1: "Urban Portability Hub",
    2: "Mid-Volume Semi-Urban",
    3: "Volatile / Under-Utilized",
}

CLUSTER_COLORS = ["#e6194B", "#3cb44b", "#4363d8", "#f58231", "#911eb4",
                   "#42d4f4", "#f032e6", "#bfef45", "#469990", "#800000"]

df = load_data()

st.title("🏪 Telangana PDS Shop Performance Dashboard")
st.caption("Interactive monitoring of Fair Price Shop clusters, anomalies & portability trends")

# ---------------- Sidebar filters ----------------
st.sidebar.header("Filters")
districts = ["All"] + sorted(df["distName"].dropna().unique().tolist())
selected_district = st.sidebar.selectbox("District", districts)

cluster_options = ["All"] + sorted(df["cluster"].unique().tolist())
selected_cluster = st.sidebar.selectbox(
    "Cluster", cluster_options,
    format_func=lambda c: "All" if c == "All" else f"{c} - {CLUSTER_NAMES.get(c, '')}"
)

filtered = df.copy()
if selected_district != "All":
    filtered = filtered[filtered["distName"] == selected_district]
if selected_cluster != "All":
    filtered = filtered[filtered["cluster"] == selected_cluster]

# ---------------- Top metrics ----------------
col1, col2, col3, col4 = st.columns(4)
col1.metric("Shops shown", len(filtered))
col2.metric("Avg Utilization Ratio", f"{filtered['utilization_ratio'].mean():.2f}")
col3.metric("Avg Portability Ratio", f"{filtered['portability_ratio'].mean():.2f}")
n_anomalies = (filtered["dbscan_cluster"] == -1).sum() if "dbscan_cluster" in filtered else 0
col4.metric("Anomalous Shops (DBSCAN)", n_anomalies)

st.divider()

# ---------------- Layout: Map + Table ----------------
map_col, table_col = st.columns([3, 2])

with map_col:
    st.subheader("Geospatial Cluster Map")
    map_points = filtered.dropna(subset=["latitude", "longitude"])
    center_lat = map_points["latitude"].mean() if len(map_points) else 17.9
    center_lon = map_points["longitude"].mean() if len(map_points) else 79.5
    m = folium.Map(location=[center_lat, center_lon], zoom_start=7)

    # Cap markers for performance - random sample if the filtered view is large
    plot_points = map_points if len(map_points) <= 2000 else map_points.sample(2000, random_state=1)

    for _, row in plot_points.iterrows():
        color = CLUSTER_COLORS[int(row["cluster"]) % len(CLUSTER_COLORS)]
        is_anomaly = row.get("dbscan_cluster", 0) == -1
        folium.CircleMarker(
            location=[row["latitude"], row["longitude"]],
            radius=6 if is_anomaly else 4,
            color="black" if is_anomaly else color,
            fill=True,
            fill_color=color,
            fill_opacity=0.8,
            weight=2 if is_anomaly else 1,
            popup=f"{row['shopNo']} ({row['distName']}) | "
                  f"{CLUSTER_NAMES.get(row['cluster'], row['cluster'])}"
                  + (" | ANOMALY" if is_anomaly else ""),
        ).add_to(m)

    if len(map_points) > 2000:
        st.caption(f"Showing a random sample of 2,000 of {len(map_points)} shops for map performance.")

    st_folium(m, width=700, height=500)

with table_col:
    st.subheader("Cluster Profile Summary")
    profile = filtered.groupby("cluster").agg(
        n_shops=("shopNo", "count"),
        avg_utilization=("utilization_ratio", "mean"),
        avg_portability=("portability_ratio", "mean"),
        avg_volatility=("volatility_cv", "mean"),
    ).round(2)
    profile.insert(0, "persona", [CLUSTER_NAMES.get(c, c) for c in profile.index])
    st.dataframe(profile, use_container_width=True)

    st.subheader("Shops in view")
    st.dataframe(
        filtered[["shopNo", "distName", "cluster", "utilization_ratio",
                  "portability_ratio", "totalRcs"]],
        use_container_width=True,
        height=250,
    )

st.divider()

# ---------------- Shop search tool ----------------
st.subheader("🔍 Shop Lookup vs Cluster Average")
shop_id_input = st.text_input("Enter shopNo (e.g. 1901001)")

if shop_id_input:
    shop_row = df[df["shopNo"].astype(str).str.strip() == shop_id_input.strip()]
    if shop_row.empty:
        st.warning(f"Shop '{shop_id_input}' not found.")
    else:
        shop_row = shop_row.iloc[0]
        cluster_id = shop_row["cluster"]
        cluster_avg = df[df["cluster"] == cluster_id][
            ["utilization_ratio", "portability_ratio", "volatility_cv",
             "rice_dependency", "avg_monthly_trans", "totalRcs"]
        ].mean()

        compare_df = pd.DataFrame({
            "This Shop": shop_row[cluster_avg.index],
            "Cluster Average": cluster_avg,
        }).round(2)

        st.write(f"**{shop_id_input}** belongs to **Cluster {cluster_id}** "
                 f"({CLUSTER_NAMES.get(cluster_id, '')})")
        st.bar_chart(compare_df)
        st.dataframe(compare_df, use_container_width=True)

        if shop_row.get("dbscan_cluster", 0) == -1:
            st.error("⚠️ This shop is flagged as a DBSCAN anomaly (noise point) — "
                      "behavior doesn't match any typical cluster.")